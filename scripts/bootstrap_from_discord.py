#!/usr/bin/env python3
"""Generate Terraform config + import blocks from an existing Discord server.

Reads the server, its roles, channels and permission overwrites through the
Discord API using the bot token, and writes:

  server.auto.tfvars   server_id
  server.tf            discord_managed_server + discord_role_everyone
  roles.tf             one discord_role per (non-bot) role
  channels.tf          categories, text, announcement, voice and forum channels
  permissions.tf       channel permission overrides
  imports.tf           import blocks so Terraform adopts what already exists

Permissions are written as `discord_permission` data sources
(e.g. `send_messages = "allow"`) so they're readable and editable.

Only the Python standard library is used.

Usage:
  DISCORD_TOKEN=... python3 scripts/bootstrap_from_discord.py --server-id 1234567890
  python3 scripts/bootstrap_from_discord.py --from-json snapshot.json   # offline / testing
"""

